import { open, B, APP, latin } from './lib.mjs';
const { b, ctx, p, errs, dump, buttons } = await open();
await p.goto(APP + '/signup'); await p.waitForTimeout(1500);
await p.getByPlaceholder('0912 123 4567').fill('09357654322'); await p.getByRole('button', { name: 'دریافت کد تأیید' }).click(); await p.waitForTimeout(1500);
const txt = await p.evaluate(() => document.body.innerText); const mm = txt.match(/کد ورود شما[^۰-۹0-9]*([۰-۹0-9]{5})/); if (!mm) { console.log(txt.slice(0, 600)); process.exit(1); } const code = latin(mm[1]); console.log('code', code);
await p.getByPlaceholder('مثلاً: سارا محمدی').fill('علی رضایی');
await p.locator('input[autocomplete=one-time-code]').fill(code); await p.waitForTimeout(500);
const go = p.getByRole('button', { name: 'ساخت حساب و ورود' }); if (await go.count()) await go.click({ timeout: 3000 }).catch(() => console.log('no click')); await p.waitForTimeout(3500);
await dump('d0-after-signup'); await buttons();
await ctx.storageState({ path: `${B}/state.json` });
await b.close(); console.log('errors', errs);
